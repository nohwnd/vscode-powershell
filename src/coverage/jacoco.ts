/**
 * Minimal JaCoCo XML parser for the shape emitted by Pester's CodeCoverage plugin.
 *
 * Pester emits three near-identical flavours of this XML and they disagree only on
 * how absolute paths are split between `<package>` and `<sourcefile>`:
 *
 *   Pester 5.x `JaCoCo`            package="src/a" sourcefile="a/Alpha.ps1"
 *   Pester 5.x `CoverageGutters`   package="src/a" sourcefile="Alpha.ps1"
 *   Pester 6.x `JaCoCo` (only)     package="src/a" sourcefile="a/Alpha.ps1"
 *
 * Neither value alone is a path relative to a well-defined root: `package` is
 * relative to Pester's internal `ReportRoot` (≈ parent of the common parent of all
 * instrumented files), while `sourcefile` is relative to the common parent itself.
 * Joining them naively produces nonsense like `src/a/a/Alpha.ps1`.
 *
 * We therefore keep the two fields raw and provide `resolveCoverageSources()`
 * which matches each parsed entry back to one of the absolute paths we asked
 * Pester to instrument, by suffix. This avoids any guesswork about ReportRoot
 * and gives the same result across all three flavours.
 *
 * The parser ignores `<class>`, `<method>`, and `<counter>` aggregates. It is
 * regex-based and assumes well-formed Pester output (no comments, no CDATA, no
 * entity references in the parts we care about). That is safe because the
 * input is always generated by Pester itself.
 */

/** One executable line with hit data, as recorded by Pester. */
export interface ParsedLineCoverage {
    /** 1-indexed line number in the source file. */
    line: number;
    /** Instructions missed on this line. */
    missed: number;
    /** Instructions covered (hit) on this line. */
    covered: number;
    /** Branches missed on this line. Pester always emits 0 today. */
    branchesMissed: number;
    /** Branches covered on this line. Pester always emits 0 today. */
    branchesCovered: number;
}

/** Raw per-file coverage as it appears in the JaCoCo XML, with forward slashes. */
export interface ParsedFileCoverage {
    /** `<package name="...">` — directory path relative to Pester's ReportRoot. */
    packagePath: string;
    /** `<sourcefile name="...">` — may be a basename or a relative subpath. */
    sourcefile: string;
    /** Per-line coverage records, in document order. */
    lines: ParsedLineCoverage[];
}

/** A `ParsedFileCoverage` matched back to one of the known absolute source paths. */
export interface ResolvedFileCoverage {
    /** Absolute path of the source file on disk. */
    absolutePath: string;
    /** The raw parser entry this resolved record came from. */
    parsed: ParsedFileCoverage;
}

const PACKAGE_RE = /<package\s+name="([^"]*)"\s*>([\s\S]*?)<\/package>/g;
const SOURCEFILE_RE =
    /<sourcefile\s+name="([^"]*)"\s*>([\s\S]*?)<\/sourcefile>/g;
const LINE_RE = /<line\b([^/>]*)\/>/g;
const ATTR_RE = /(\w+)="([^"]*)"/g;

/**
 * Parse a JaCoCo XML report produced by Pester.
 *
 * @param xml The XML document text.
 * @returns One `ParsedFileCoverage` per `<sourcefile>` element.
 * @throws Error if the document does not contain a `<report>` root element.
 */
export function parseJaCoCoXml(xml: string): ParsedFileCoverage[] {
    if (!/<report\b/.test(xml)) {
        throw new Error(
            "JaCoCo parse error: input does not contain a <report> element.",
        );
    }

    const files: ParsedFileCoverage[] = [];

    PACKAGE_RE.lastIndex = 0;
    let packageMatch: RegExpExecArray | null;
    while ((packageMatch = PACKAGE_RE.exec(xml)) !== null) {
        const packagePath = normaliseSlashes(packageMatch[1]);
        const packageBody = packageMatch[2];

        SOURCEFILE_RE.lastIndex = 0;
        let sourceMatch: RegExpExecArray | null;
        while ((sourceMatch = SOURCEFILE_RE.exec(packageBody)) !== null) {
            const sourcefile = normaliseSlashes(sourceMatch[1]);
            const sourceBody = sourceMatch[2];

            const lines: ParsedLineCoverage[] = [];
            LINE_RE.lastIndex = 0;
            let lineMatch: RegExpExecArray | null;
            while ((lineMatch = LINE_RE.exec(sourceBody)) !== null) {
                const attrs = parseAttributes(lineMatch[1]);
                const nr = toInt(attrs.nr);
                if (nr === undefined) {
                    continue;
                }
                lines.push({
                    line: nr,
                    missed: toInt(attrs.mi) ?? 0,
                    covered: toInt(attrs.ci) ?? 0,
                    branchesMissed: toInt(attrs.mb) ?? 0,
                    branchesCovered: toInt(attrs.cb) ?? 0,
                });
            }

            files.push({ packagePath, sourcefile, lines });
        }
    }

    return files;
}

/**
 * Match each parsed entry to an absolute path from a known candidate list.
 *
 * The match is done by suffix on the *normalised* path
 * `package + '/' + sourcefile_without_redundant_prefix`. This deliberately
 * collapses the v5 JaCoCo / v5 CoverageGutters / v6 JaCoCo layout differences
 * (see the comment at the top of this file) into the same suffix, so the same
 * resolution logic works regardless of Pester version and output format.
 *
 * If a parsed entry cannot be matched, it is omitted from the result and the
 * `unresolved` array contains it instead, for diagnostic logging by the caller.
 */
export function resolveCoverageSources(
    parsed: readonly ParsedFileCoverage[],
    candidateAbsolutePaths: readonly string[],
): { resolved: ResolvedFileCoverage[]; unresolved: ParsedFileCoverage[] } {
    const normalisedCandidates = candidateAbsolutePaths.map((p) =>
        normaliseSlashes(p),
    );
    const resolved: ResolvedFileCoverage[] = [];
    const unresolved: ParsedFileCoverage[] = [];

    for (const entry of parsed) {
        const suffix = buildMatchSuffix(entry.packagePath, entry.sourcefile);
        const match = findBestSuffixMatch(suffix, normalisedCandidates);
        if (match === undefined) {
            unresolved.push(entry);
            continue;
        }
        resolved.push({
            absolutePath: candidateAbsolutePaths[match],
            parsed: entry,
        });
    }

    return { resolved, unresolved };
}

function buildMatchSuffix(packagePath: string, sourcefile: string): string {
    const pkg = packagePath.replace(/\/+$/u, "");
    const file = sourcefile.replace(/^\.\//u, "");

    // Pester 5.x JaCoCo and Pester 6.x both encode the leaf of `package` again
    // as the prefix of `sourcefile` (e.g. package="src/a" + sourcefile="a/Foo.ps1").
    // Strip the redundant prefix so we get a single canonical suffix.
    let cleaned = file;
    if (pkg !== "" && pkg !== ".") {
        const lastPackageSegment = pkg.substring(pkg.lastIndexOf("/") + 1);
        const prefix = `${lastPackageSegment}/`;
        if (cleaned.startsWith(prefix)) {
            cleaned = cleaned.substring(prefix.length);
        }
    }

    if (pkg === "" || pkg === ".") {
        return cleaned;
    }
    return `${pkg}/${cleaned}`;
}

function findBestSuffixMatch(
    suffix: string,
    candidates: readonly string[],
): number | undefined {
    const lowered = suffix.toLowerCase();
    let best: number | undefined;
    let bestScore = -1;
    for (let i = 0; i < candidates.length; i++) {
        const candidate = candidates[i].toLowerCase();
        if (candidate === lowered || candidate.endsWith(`/${lowered}`)) {
            const score = lowered.length;
            if (score > bestScore) {
                best = i;
                bestScore = score;
            }
        }
    }
    return best;
}

function parseAttributes(fragment: string): Record<string, string> {
    const result: Record<string, string> = {};
    ATTR_RE.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = ATTR_RE.exec(fragment)) !== null) {
        result[m[1]] = m[2];
    }
    return result;
}

function toInt(value: string | undefined): number | undefined {
    if (value === undefined) {
        return undefined;
    }
    const n = Number.parseInt(value, 10);
    return Number.isNaN(n) ? undefined : n;
}

function normaliseSlashes(input: string): string {
    return input.replace(/\\/g, "/");
}
